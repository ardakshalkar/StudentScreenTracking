import {test,expect} from '@playwright/test';
import WebSocket from 'ws';
import {mkdir} from 'node:fs/promises';

test('teacher sees authenticated image payloads, focuses, records, and ends capture',async({page})=>{
  const browserErrors:string[]=[];page.on('pageerror',error=>browserErrors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Teacher password').fill('ui-test-password-only');
  await page.getByRole('button',{name:'Open dashboard'}).click();
  await expect(page.getByRole('heading',{name:'Your classroom, live.'})).toBeVisible();
  await page.getByRole('textbox',{name:'Course name',exact:true}).fill('Python programming');
  await page.getByRole('textbox',{name:'Session title',exact:true}).fill('Browser integration test');
  await page.getByRole('button',{name:'Start session +'}).click();
  await expect(page.getByText('SESSION LIVE',{exact:false})).toBeVisible();
  const headers={Origin:'http://localhost:5179'};
  const session=(await (await page.request.get('/api/sessions')).json())[0];
  const joined=await (await page.request.post('/api/join',{headers,data:{name:'Synthetic browser test',student_id:'UI-001',code:session.code}})).json();
  const socket=new WebSocket('ws://127.0.0.1:8012/api/ws/student',{origin:'chrome-extension://'+'a'.repeat(32)});
  const messages:any[]=[];
  socket.on('message',raw=>messages.push(JSON.parse(raw.toString())));
  await new Promise<void>((resolve,reject)=>{socket.once('open',resolve);socket.once('error',reject);});
  socket.send(JSON.stringify({token:joined.token}));
  await expect.poll(()=>messages.some(body=>body.type==='ready')).toBe(true);
  const raw=await page.evaluate(()=>{
    const canvas=document.createElement('canvas');canvas.width=1280;canvas.height=720;
    const ctx=canvas.getContext('2d')!;ctx.fillStyle='#162832';ctx.fillRect(0,0,1280,720);
    ctx.font='22px monospace';ctx.fillStyle='#b4dabf';ctx.fillText('SYNTHETIC BROWSER INTEGRATION TEST',30,45);
    const lines=['def calculate_average(values):','    total = sum(values)','    return total / len(values)','','scores = [84, 92, 88, 95]','print(calculate_average(scores))'];
    ctx.fillStyle='#dae5e9';lines.forEach((line,i)=>ctx.fillText(line,30,110+i*38));
    return canvas.toDataURL('image/webp',.9).split(',')[1];
  });
  socket.send(Buffer.from(raw,'base64'));
  await expect(page.getByRole('img',{name:"Synthetic browser test's shared screen",exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Synthetic browser test/}).click();
  await expect(page.getByRole('dialog',{name:'Focused student screen'})).toBeVisible();
  await expect.poll(()=>messages.some(body=>body.type==='quality'&&body.mode==='focused')).toBe(true);
  await page.keyboard.press('Escape');
  await expect.poll(()=>messages.some(body=>body.type==='quality'&&body.mode==='overview')).toBe(true);
  await page.getByLabel('Search students').fill('missing-student');
  await expect(page.getByRole('img',{name:"Synthetic browser test's shared screen",exact:true})).toHaveCount(0);
  await page.getByLabel('Search students').fill('UI-001');
  await page.getByRole('button',{name:'Enable recording',exact:true}).click();
  await expect(page.getByRole('button',{name:'Pause recording',exact:true})).toBeVisible();
  await expect.poll(async()=> (await(await page.request.get(`/api/sessions/${session.id}/samples`)).json()).length).toBe(1);
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/dashboard-browser-test.png',fullPage:true});
  await page.getByRole('button',{name:'Playback ↗',exact:true}).click();
  const playback=page.getByRole('dialog',{name:'Recorded session playback'});
  await expect(playback.getByRole('img',{name:'Recorded classroom screenshot'})).toBeVisible();
  await playback.getByRole('button',{name:'Close ×'}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'End session',exact:true}).click();
  await expect.poll(()=>messages.some(body=>body.type==='session_ended')).toBe(true);
  socket.close();
  expect(browserErrors).toEqual([]);
});
